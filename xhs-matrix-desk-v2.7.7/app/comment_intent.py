def review_hint(text):
    text = str(text or '')
    invitation = bool(re.search(r'(?:请|可以|麻烦|求)?(?:私信|私聊|私发)(?:一下|联系|发给)?我|给我(?:发)?(?:私信|私聊)|(?:私信|私聊)我', text))
    denied = bool(re.search(r'(?:不要|别|不想|不接受|拒绝|禁止|无需|不用).{0,8}(?:私信|私聊|私发)|(?:私信|私聊).{0,4}(?:勿扰|免打扰)', text))
    if invitation and not denied:
        return {'review_hint':'私信请求候选 · 须核对原文', 'request_candidate': True}
    if any(word in text for word in ('多少钱','价格','报价','预约','地址','在哪','咨询','推荐','想做')):
        return {'review_hint':'有咨询语句 · 人工查看', 'request_candidate': False}
    return {'review_hint':'一般评论', 'request_candidate': False}
